/**
 * Test case dataset for the BrowserReflex advisory safety test suite.
 *
 * Covers six families with 190+ data-driven test cases:
 * 1. payment: English and Bangla controls, checkout steps with continue/next, wallet and pay buttons
 * 2. destructive: delete account, wipe, remove all, drop, rm -rf, force push, reset --hard, clear data
 * 3. outbound: send, post, publish, share, email, submit message
 * 4. secrets: credentials and card numbers in text entered by actions, built dynamically at run time
 * 5. prompt_injection: text attempting to lower caution or invent caution on harmless pages
 * 6. benign: actions that must remain allow so false positives are strictly measured
 *
 * The safety check is advisory: it reports caution and never prevents an agent from acting.
 */

import type { ActionGuardInput } from '../../src/tools/action_guard.js';

export type SafetyCaseFamily =
  'payment' | 'destructive' | 'outbound' | 'secrets' | 'prompt_injection' | 'benign';

export interface PageCheckExpectation {
  readonly expectRisky: boolean;
  readonly expectedRiskFamily?: 'payment' | 'destructive' | 'outbound';
}

export interface SafetyTestCase {
  readonly id: string;
  readonly family: SafetyCaseFamily;
  readonly description: string;
  readonly input: ActionGuardInput;
  readonly expectedVerdict: 'allow' | 'ask_user' | 'block';
  readonly pageCheckExpectation?: PageCheckExpectation;
  readonly secretPayload?: string;
}

